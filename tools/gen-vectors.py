#!/usr/bin/env python3
"""Regenerate tests/vectors.txt from Python's hashlib / hmac.

Run from the repository root:  python3 -I tools/gen-vectors.py > tests/vectors.txt

The xTalk test stack (tests/libPBKDF2Tests.livecodescript) reads this file, so
every value the library is checked against comes from an independent
implementation. The first RFC 6070 and RFC 7914 vectors are also published, so
the two sources agree.
"""
import base64
import hashlib
import hmac


def ab64(b: bytes) -> str:
    """passlib's adapted base64: standard alphabet, '+' -> '.', no padding."""
    return base64.b64encode(b).decode().rstrip("=").replace("+", ".")


print("# libPBKDF2 known-answer vectors. Generated by tools/gen-vectors.py; do not edit.")
print("# pbkdf2<TAB>digest<TAB>password-hex<TAB>salt-hex<TAB>iterations<TAB>dklen<TAB>expected-hex")
pbkdf2_cases = [
    # RFC 6070 (PBKDF2-HMAC-SHA1)
    ("sha1", b"password", b"salt", 1, 20),
    ("sha1", b"password", b"salt", 2, 20),
    ("sha1", b"password", b"salt", 4096, 20),
    ("sha1", b"passwordPASSWORDpassword", b"saltSALTsaltSALTsaltSALTsaltSALTsalt", 4096, 25),
    ("sha1", b"pass\x00word", b"sa\x00lt", 4096, 16),
    # RFC 7914 section 11 (PBKDF2-HMAC-SHA256)
    ("sha256", b"passwd", b"salt", 1, 64),
    # widely published SHA-256 vector
    ("sha256", b"password", b"salt", 4096, 32),
    # the ECHOindications-API scheme: text salt, 10,000 rounds, 32 bytes
    ("sha256", b"testpassword123", b"abcdefghijklmnopqrstuvwxyz012345", 10000, 32),
    # other digests
    ("sha512", b"password", b"salt", 4096, 64),
    ("sha224", b"password", b"salt", 1000, 28),
    ("sha384", b"password", b"salt", 1000, 48),
    ("md5", b"password", b"salt", 1000, 16),
    # UTF-8 password, binary salt with high bytes, dklen spanning two blocks
    ("sha256", "pässwörd€".encode(), bytes(range(0, 256, 17)), 1000, 40),
    # password longer than the HMAC block size (key gets pre-hashed)
    ("sha512", b"x" * 200, b"salt", 10, 64),
    ("sha256", b"y" * 65, b"salt", 10, 32),
    # dklen not a multiple of the digest length, three blocks
    ("sha1", b"password", b"salt", 3, 45),
]
for d, p, s, c, dk in pbkdf2_cases:
    print("\t".join(["pbkdf2", d, p.hex(), s.hex(), str(c), str(dk), hashlib.pbkdf2_hmac(d, p, s, c, dk).hex()]))

print("# hmac<TAB>digest<TAB>key-hex<TAB>message-hex<TAB>expected-hex")
hmac_cases = []
for d in ["md5", "sha1", "sha224", "sha256", "sha384", "sha512"]:
    hmac_cases.append((d, b"\x0b" * 20, b"Hi There"))                     # RFC 4231 case 1
hmac_cases.append(("sha256", b"Jefe", b"what do ya want for nothing?"))     # RFC 4231 case 2
hmac_cases.append(("sha256", b"\xaa" * 131, b"Test Using Larger Than Block-Size Key - Hash Key First"))  # case 6
hmac_cases.append(("sha512", b"\xaa" * 131, b"Test Using Larger Than Block-Size Key - Hash Key First"))
hmac_cases.append(("sha256", b"", b""))                                     # empty key and message
hmac_cases.append(("sha256", b"k" * 64, b"exactly one block of key"))       # key == block size
for d, k, m in hmac_cases:
    print("\t".join(["hmac", d, k.hex(), m.hex(), hmac.new(k, m, d).hexdigest()]))

print("# passlib<TAB>password-utf8-hex<TAB>hash-string   (must verify)")
passlib_cases = [
    ("sha256", "password", bytes(range(1, 17)), 29000),
    ("sha1", "hunter2", b"0123456789abcdef", 131000),
    ("sha512", "pässwörd", b"ABCDEFGHIJKLMNOP", 25000),
    ("sha256", "", b"\xff" * 16, 1000),  # empty password
]
for d, p, s, c in passlib_cases:
    h = hashlib.pbkdf2_hmac(d, p.encode(), s, c)
    print("\t".join(["passlib", p.encode().hex(), f"$pbkdf2-{d}${c}${ab64(s)}${ab64(h)}"]))
